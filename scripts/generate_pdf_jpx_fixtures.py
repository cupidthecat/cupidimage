#!/usr/bin/env python3
"""Build owned JPEG 2000 image and embedded-opacity assets."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_images import fixture
from test_pdf_jpx_containers import jp2, source_values, palette, cmap, cdef, colr


def fixtures():
    rows = json.loads(Path('tests/fixtures/pdf-jpx-samples.json').read_text())['cases']
    rgb = next(r for r in rows if r['name'] == 'RGB-unsigned')
    gray = next(r for r in rows if r['name'] == 'L-unsigned')
    attrs = '/Width 3 /Height 2 /ColorSpace /DeviceRGB /Filter /JPXDecode'
    pixels = list(zip(*source_values(rgb)))
    plain = bytes(c for y in range(16) for x in range(24)
                  for c in (*pixels[(y // 8) * 3 + x // 8], 255))
    yield 'jpx-native-rgb', fixture(jp2(rgb), attrs), plain
    entries = [[0, 128, 255, 255 if i % 2 else 0] for i in range(256)]
    extra = palette(entries, [7] * 4) + cmap([(0, 1, c) for c in range(4)])
    extra += cdef([(0, 0, 1), (1, 0, 2), (2, 0, 3), (3, 1, 0)])
    payload = jp2(gray, extra).replace(colr(17), colr(16), 1)
    values = source_values(gray)[0]
    masked = bytes(c for y in range(16) for x in range(24) for c in
                   ((0, 128, 255, 255) if values[(y // 8) * 3 + x // 8] % 2 else (128, 128, 128, 255)))
    yield 'jpx-palette-opacity', fixture(payload, attrs + ' /SMaskInData 1'), masked


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    reference = Path('tests/fixtures/pdf-image-reference.json')
    data = json.loads(reference.read_text())
    for name, pdf, pixels in fixtures():
        path = Path('assets/pdf/reference') / (name + '.pdf')
        pdf = pdf.replace(b'%PDF-1.4', b'%PDF-1.7', 1)
        row = {'asset': str(path), 'width': 24, 'height': 16,
               'rgba_zlib': base64.b64encode(zlib.compress(pixels, 9)).decode(), 'tolerance': 0,
               'provenance': 'Authored lossless JPEG 2000 samples, expanded with literal RGB and opacity values.'}
        index = next((i for i, case in enumerate(data['cases']) if case['asset'] == str(path)), None)
        if args.check:
            assert path.read_bytes() == pdf, 'Regenerate ' + str(path)
            assert index is not None and data['cases'][index] == row, 'Regenerate JPEG 2000 references'
        else:
            path.write_bytes(pdf)
            if index is None:
                data['cases'].append(row)
            else:
                data['cases'][index] = row
    if not args.check:
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF JPEG 2000 fixtures: generated bytes verified' if args.check else 'Wrote PDF JPEG 2000 fixtures')


if __name__ == '__main__':
    main()
