#!/usr/bin/env python3
"""Build an owned page exercising ICC lookup-based destination spaces."""
import argparse
from pathlib import Path
from test_pdf_pages import document
from test_pdf_forms import form
from test_pdf_type3 import stream
from test_pdf_icc import curve, gamma
from test_pdf_icc_lut import profile, lut as forward_lut
from test_pdf_icc_reverse import lut, mba, table
from test_pdf_intents import tags


def build():
    objects={5:'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',30:'<< /ca .5 >>'}
    labels=('16-bit XYZ tables','8-bit Lab tables','XYZ multistage tables','Lab multistage tables')
    content=['BT /Label 14 Tf 12 222 Td (ICC destination lookup pipelines) Tj ET']
    xobjects=[]
    source='[/CalRGB << /WhitePoint [.964202880859375 1 .8249053955078125] >>]'
    for index in range(4):
        lab=index%2==1
        reverse=lut(3,8 if lab else 16) if index<2 else mba(3,b=[gamma(2)]*3,
            matrix=(1,0,0,0,1,0,0,0,1,0,0,0),m=[curve()]*3,table=table(3),a=[gamma(.5)]*3)
        data=tags(profile(forward_lut(),lab=lab),{b'B2A0':reverse})
        objects[100+index]=stream(data,'/N 3')
        blend=f'[/ICCBased {100+index} 0 R]'
        objects[20+index]=form('/Source cs .15 .25 .4 scn 0 0 144 60 re f /Half gs .4 .3 .15 scn 24 12 96 36 re f',
            '/BBox [0 0 144 60] /Group << /S /Transparency /I true /CS '+blend+' >> /Resources << /ColorSpace << /Source '+source+' >> /ExtGState << /Half 30 0 R >> >>')
        x=12+(index%2)*180;y=132-(index//2)*92
        content.append(f'BT /Label 9 Tf {x} {y+67} Td ({labels[index]}) Tj ET')
        content.append(f'q 1 0 0 1 {x} {y} cm /G{index} Do Q')
        xobjects.append(f'/G{index} {20+index} 0 R')
    content.append('BT /Label 8 Tf 12 19 Td (Authored transforms test stage order and blending, not a physical device profile.) Tj ET')
    return document('/MediaBox [0 0 360 240] /Resources << /Font << /Label 5 0 R >> /XObject << '+' '.join(xobjects)+' >> >>',stream='\n'.join(content),extra=objects)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/icc-destination-blending.pdf';data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the ICC destination fixture'
        print('PDF ICC destination fixture: generated bytes verified')
    else:path.write_bytes(data);print(f'Wrote {path.name}')


if __name__=='__main__':main()
