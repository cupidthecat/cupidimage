#!/usr/bin/env python3
"""Build an owned page comparing ordinary and scoped Type 1 font declarations."""

import argparse
from pathlib import Path
from pdf_type1_scopes_fixture import program
from test_pdf_pages import document
from test_pdf_type3 import stream

CASES = [
    ("nested-leniv", "Nested lenIV"),
    ("nested-binary-subrs", "Nested binary Subrs"),
    ("nested-charstrings", "Nested CharStrings"),
    ("global-reader", "Inherited reader"),
    ("active-clear-definer", "Inherited definer"),
    ("clear-sibling-matrix", "Sibling dictionary"),
]


def build(controls=False):
    objects = {8: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"}

    def font(number, variant):
        data, clear, encrypted = program(variant)
        objects[number] = (
            f"<< /Type /Font /Subtype /Type1 /BaseFont /CupidShapes /Encoding /WinAnsiEncoding /FirstChar 65 /LastChar 65 /Widths [600] /FontDescriptor {number+1} 0 R >>".encode()
        )
        objects[number + 1] = (
            f"<< /Type /FontDescriptor /FontName /CupidShapes /Flags 32 /FontBBox [0 -200 1000 1000] /Ascent 800 /Descent -200 /ItalicAngle 0 /CapHeight 600 /StemV 80 /FontFile {number+2} 0 R >>".encode()
        )
        objects[number + 2] = stream(data, f"/Length1 {clear} /Length2 {encrypted} /Length3 0")

    font(5, "control")
    names = ["/Control 5 0 R", "/Label 8 0 R"]
    content = [
        "BT /Label 16 Tf 18 278 Td (Type 1 dictionary scopes) Tj ET",
        "BT /Label 9 Tf 18 261 Td (Each pair should have identical glyph geometry.) Tj ET",
        "BT /Label 10 Tf 24 239 Td (Control) Tj ET",
        "BT /Label 10 Tf 80 239 Td (Declaration) Tj ET",
        "BT /Label 10 Tf 215 239 Td (Scoped program) Tj ET",
    ]
    for i, (variant, label) in enumerate(CASES):
        number = 10 + i * 3
        font(number, "control" if controls else variant)
        names.append(f"/Scope{i} {number} 0 R")
        y = 210 - i * 35
        content += [
            f"0 g BT /Label 9 Tf 80 {y+4} Td ({label}) Tj ET",
            f"0.1 0.25 0.65 rg BT /Control 24 Tf 24 {y} Td (AAA) Tj ET",
            f"BT /Scope{i} 24 Tf 215 {y} Td (AAA) Tj ET",
        ]
    return document(
        "/MediaBox [0 0 360 300] /Resources << /Font << " + " ".join(names) + " >> >>",
        "",
        " ".join(content),
        objects,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "assets/pdf/type1-dictionary-scopes.pdf"
    if args.check:
        assert path.read_bytes() == build(), "Regenerate the Type 1 dictionary-scope sample"
        print("Type 1 dictionary-scope sample: generated bytes verified")
    else:
        path.write_bytes(build())
