#!/usr/bin/env python3
"""Convert the pinned, licensed standard-font CFF arrays to C99 declarations."""
import hashlib
import json
import re
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/standard-fonts'
FONTS = {
    'Courier':'FoxitFixed', 'Courier-Bold':'FoxitFixedBold',
    'Courier-Oblique':'FoxitFixedItalic', 'Courier-BoldOblique':'FoxitFixedBoldItalic',
    'Helvetica':'FoxitSans', 'Helvetica-Bold':'FoxitSansBold',
    'Helvetica-Oblique':'FoxitSansItalic', 'Helvetica-BoldOblique':'FoxitSansBoldItalic',
    'Times-Roman':'FoxitSerif', 'Times-Bold':'FoxitSerifBold',
    'Times-Italic':'FoxitSerifItalic', 'Times-BoldItalic':'FoxitSerifBoldItalic',
    'Symbol':'FoxitSymbol', 'ZapfDingbats':'FoxitDingbats',
}
def font_bytes(stem):
    text = (SOURCE / (stem+'.cpp')).read_text()
    count = int(re.search(r'std::array<uint8_t, (\d+)>',text).group(1))
    body = text.split('= {{',1)[1].split('}};',1)[0]
    data = bytes(int(v,16) for v in re.findall(r'0x[0-9a-fA-F]+',body))
    assert len(data) == count
    return data

def generate():
    for row in json.loads((SOURCE/'manifest.json').read_text())['files']:
        assert hashlib.sha256((SOURCE/row['file']).read_bytes()).hexdigest() == row['sha256']
    lines = ['/* Generated by scripts/generate_pdf_standard_outlines.py.',
             ' * Modified representation: C99 arrays; font bytes are unchanged.',
             ' * Copyright 2014 The PDFium Authors.',
             ' * Original code copyright 2014 Foxit Software Inc. http://www.foxitsoftware.com',
             ' * BSD-style license: see third_party/standard-fonts/LICENSE.',
             ' * Include THIRD_PARTY_NOTICES.md with binary distributions. */']
    for i,(name,stem) in enumerate(sorted(FONTS.items())):
        data=font_bytes(stem)
        lines.append(f'static const unsigned char standard_outline_{i}[] = {{')
        lines.extend('    '+','.join(f'0x{v:02x}' for v in data[j:j+20])+',' for j in range(0,len(data),20))
        lines.append('};')
    lines.append('static const pdf_standard_outline standard_outlines[] = {')
    lines.extend(f'    {{"{name}", standard_outline_{i}, sizeof(standard_outline_{i})}},' for i,name in enumerate(sorted(FONTS)))
    return '\n'.join(lines+['};',''])

if __name__ == '__main__':
    import sys
    target=ROOT/'src/formats/pdf/fonts/standard_outlines.inc'
    value=generate()
    if '--check' in sys.argv: assert target.read_text()==value, 'Regenerate standard font outlines'
    else: target.write_text(value)
