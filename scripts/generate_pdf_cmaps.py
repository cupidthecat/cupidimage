#!/usr/bin/env python3
"""Compile pinned standard encoding CMaps without network access."""
import hashlib
import json
from pathlib import Path
import re
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/adobe-cmaps'


def generate():
    manifest = json.loads((SOURCE / 'manifest.json').read_text())
    names = {record['name'] for record in manifest['maps']}
    chunks = ['/* Generated by scripts/generate_pdf_cmaps.py.\n'
              ' * Adobe CMap data: see third_party/adobe-cmaps/LICENSE and THIRD_PARTY_NOTICES.md. */\n']
    records = []
    for index, record in enumerate(manifest['maps']):
        data = (SOURCE / 'CMap' / record['name']).read_bytes()
        assert hashlib.sha256(data).hexdigest() == record['sha256'], record['name']
        parents = re.findall(rb'^/([^\s]+)\s+usecmap\s*$', data, re.M)
        assert len(parents) <= 1
        parent = parents[0].decode('ascii') if parents else ''
        assert not parent or parent in names
        packed = zlib.compress(data, 9)
        chunks.append(f'static const unsigned char cmap_data_{index}[] = {{\n')
        chunks.extend('    ' + ','.join(str(n) for n in packed[i:i+24]) + ',\n'
                      for i in range(0, len(packed), 24))
        chunks.append('};\n')
        records.append(f'    {{"{record["name"]}", "{parent}", cmap_data_{index}, '
                       f'sizeof(cmap_data_{index}), {len(data)}}},\n')
    chunks.append('static const pdf_predefined_cmap cmap_resources[] = {\n')
    chunks.extend(records)
    chunks.append('};\n')
    return ''.join(chunks)


if __name__ == '__main__':
    (ROOT / 'src/formats/pdf/fonts/cmap_data.inc').write_text(generate())
