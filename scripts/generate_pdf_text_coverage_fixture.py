#!/usr/bin/env python3
"""Build the owned PDF text-coverage sample; use --check to verify its bytes."""
import argparse
from pathlib import Path
from test_pdf_embedded_fonts import fixture

CONTENT = '''
BT /Label 14 Tf 12 158 Td (Outline text coverage) Tj ET
BT /Label 9 Tf 12 141 Td (Use --pdf-text-aa to compare glyph edges.) Tj ET
0.15 0.3 0.8 rg BT /F 18 Tf 12.1875 112.1875 Td (ACFG) Tj ET
0.8 0.2 0.1 rg BT /F 27 Tf 12.375 76.375 Td (ACFG) Tj ET
0.1 0.5 0.2 rg BT /F 18 Tf 1 .25 -.125 1 20 37 Tm (ACFG) Tj ET
0 0 0 rg BT /Label 9 Tf 12 14 Td (Text fills only; strokes and clips remain binary.) Tj ET
'''
PAGE = b'''<< /Type /Page /Parent 2 0 R /Contents 4 0 R
/MediaBox [0 0 240 180] /Resources << /Font << /F 5 0 R /Label 11 0 R >> >> >>'''
LABEL = b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'


def build():
    return fixture(CONTENT, extra={3: PAGE, 11: LABEL})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1]/'assets/pdf/text-coverage.pdf'
    data = build()
    if args.check:
        assert path.read_bytes() == data, 'Regenerate the owned text-coverage sample'
        print('PDF text coverage fixture: generated bytes verified')
    else:
        path.write_bytes(data)
        print(f'Wrote {path.relative_to(path.parents[2])}')


if __name__ == '__main__':
    main()
