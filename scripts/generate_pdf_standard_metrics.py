#!/usr/bin/env python3
"""Generate immutable standard PDF font metrics from the pinned Adobe AFMs."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/adobe-core14'

def metrics(path):
    entries = {}
    encoding = {}
    for line in path.read_text().splitlines():
        if not line.startswith('C '):
            continue
        fields = dict(part.strip().split(' ', 1) for part in line.split(';') if part.strip())
        name, width, code = fields['N'], int(fields['WX']), int(fields['C'])
        entries[name] = width
        if 0 <= code <= 255:
            encoding[code] = name
    return entries, encoding

def generate():
    manifest = json.loads((SOURCE / 'manifest.json').read_text())
    for entry in manifest['files']:
        assert hashlib.sha256((SOURCE / entry['file']).read_bytes()).hexdigest() == entry['sha256']
    output = ['/* Generated by scripts/generate_pdf_standard_metrics.py. Do not edit.',
              ' * Derived from Adobe AFM data; see third_party/adobe-core14/readme.txt.',
              ' * This generated representation is not an original Adobe file. */']
    fonts = []
    for index, path in enumerate(sorted(SOURCE.glob('*.afm'))):
        entries, encoding = metrics(path)
        names = ['.notdef'] + sorted(name for name in entries if name != '.notdef')
        ids = {name: i for i, name in enumerate(names)}
        output.append(f'static const pdf_standard_metric metrics_{index}[] = {{')
        output.extend(f'    {{"{name}", {entries.get(name, 0)}}},' for name in names)
        output.append('};')
        output.append(f'static const unsigned encoding_{index}[256] = {{')
        values = [str(ids.get(encoding.get(i), 0)) for i in range(256)]
        output.extend('    ' + ', '.join(values[i:i+16]) + ',' for i in range(0,256,16))
        output.append('};')
        fonts.append(f'    {{"{path.stem}", metrics_{index}, {len(names)}, encoding_{index}}},')
    output += ['static const pdf_standard_font standard_fonts[] = {', *fonts, '};', '']
    return '\n'.join(output)

if __name__ == '__main__':
    import sys
    target = ROOT / 'src/formats/pdf/fonts/standard_metrics.inc'
    value = generate()
    if '--check' in sys.argv:
        assert target.read_text() == value, 'Regenerate standard font metrics'
    else:
        target.write_text(value)
