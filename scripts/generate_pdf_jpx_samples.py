#!/usr/bin/env python3
"""Author small JPEG 2000 samples; Pillow is needed only for regeneration."""
import base64
import io
import json
from pathlib import Path
import struct
import zlib
from PIL import Image, features


def fixture(name, mode, size, **options):
    width,height=size
    bits=16 if mode=='I;16' else 8
    channels=1 if mode in ('L','I;16') else len(mode)
    maximum=(1<<bits)-1
    values=[((x*73+y*149+x*y*17+c*41) & maximum) for y in range(height) for x in range(width) for c in range(channels)]
    if mode=='I;16':
        values=[(v*257)&65535 for v in values]
        image=Image.frombytes(mode,size,struct.pack('<'+str(len(values))+'H',*values))
    else:image=Image.frombytes(mode,size,bytes(values))
    output=io.BytesIO()
    image.save(output,format='JPEG2000',no_jp2=True,num_resolutions=options.pop('num_resolutions',1),**options)
    data=output.getvalue()
    oracle='literal lossless input samples'
    if options.get('irreversible',False):
        with Image.open(io.BytesIO(data)) as decoded:values=list(decoded.tobytes())
        oracle='independent installed decoder samples'
    elif options.get('signed',False):
        values=[(v+(1<<(bits-1)))&maximum for v in values]
    planar=[values[i] for c in range(channels) for i in range(c,len(values),channels)]
    payload=struct.pack('>'+str(len(planar))+'I',*planar)
    return {'name':name,'width':width,'height':height,'components':channels,'precision':bits,
            'origin':list(options.get('offset',(0,0))),'signed':int(options.get('signed',False)),'oracle':oracle,
            'codestream':base64.b64encode(data).decode(),
            'samples_u32be_zlib':base64.b64encode(zlib.compress(payload,9)).decode()}


def main():
    cases=[]
    for mode in ('L','LA','RGB','RGBA','CMYK','I;16'):
        for signed in (False,True):
            cases.append(fixture(mode+'-'+('signed' if signed else 'unsigned'),mode,(3,2),signed=signed))
    for progression in ('LRCP','RLCP','RPCL','PCRL','CPRL'):
        cases.append(fixture('tiled-'+progression,'RGB',(17,13),num_resolutions=3,
                             tile_size=(8,8),quality_layers=[8,4,0],mct=1,progression=progression,
                             codeblock_size=(4,4),precinct_size=(8,8),plt=True))
    cases.append(fixture('offset-tiles','RGB',(17,13),num_resolutions=3,tile_size=(8,8),
                         offset=(1,3),tile_offset=(0,0),mct=1))
    cases.append(fixture('gray16-wavelet','I;16',(17,13),num_resolutions=3))
    cases.append(fixture('rgb-irreversible','RGB',(17,13),num_resolutions=3,mct=1,irreversible=True,quality_layers=[4]))
    root=Path(__file__).resolve().parents[1]
    (root/'tests/fixtures/pdf-jpx-samples.json').write_text(json.dumps({'provenance':'Owned sample patterns; generated by scripts/generate_pdf_jpx_samples.py','encoder_version':features.version_codec('jpg_2000'),'cases':cases},indent=2)+'\n')
    print(f'Wrote {len(cases)} owned JPEG 2000 sample fixtures')


if __name__=='__main__':main()
