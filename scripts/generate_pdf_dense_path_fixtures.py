#!/usr/bin/env python3
"""Build owned dense-path and localized-clipping fixtures."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_pages import document


def fixtures():
    dense = document('/MediaBox [0 0 18 12]',
                     stream='0 0 18 12 re ' * 1300 + '1 0 0 rg f')
    clip = document('/MediaBox [0 0 612 792]',
                    stream='q 0 0 12 12 re W n Q ' * 400 +
                           '0 0 12 12 re W n 0 g 0 0 612 792 re f')
    yield 'dense-vector-path.pdf', dense, 24, 16, bytes((255, 0, 0, 255)) * (24 * 16)
    pixels = bytes(v for y in range(1056) for x in range(816)
                   for v in ((0, 0, 0, 255) if x < 16 and y >= 1040 else (255,) * 4))
    yield 'localized-clip-work.pdf', clip, 816, 1056, pixels


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    reference = root / 'tests/fixtures/pdf-image-reference.json'
    data = json.loads(reference.read_text())
    for name, content, width, height, pixels in fixtures():
        asset = 'assets/pdf/' + name
        path = root / asset
        row = {'asset': asset, 'width': width, 'height': height,
               'rgba_zlib': base64.b64encode(zlib.compress(pixels, 9)).decode(),
               'tolerance': 0,
               'provenance': 'Literal expected pixels for owned opaque geometry on integer device boundaries.'}
        index = next((i for i, item in enumerate(data['cases']) if item['asset'] == asset), None)
        if args.check:
            assert path.read_bytes() == content, 'Regenerate ' + name
            assert index is not None and data['cases'][index] == row, 'Regenerate ' + asset + ' reference'
        else:
            path.write_bytes(content)
            if index is None:
                data['cases'].append(row)
            else:
                data['cases'][index] = row
    if not args.check:
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF dense-path fixtures: generated bytes verified' if args.check else 'Wrote PDF dense-path fixtures')


if __name__ == '__main__':
    main()
