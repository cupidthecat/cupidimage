#!/usr/bin/env python3
"""Build an owned standalone catalog-bound recovery fixture and literal oracle."""
import base64
import json
from pathlib import Path
import sys
import zlib
from test_pdf_xref import sparse_catalog

ROOT = Path(__file__).resolve().parents[1]

if __name__ == '__main__':
    pdf = sparse_catalog()
    pdf.table(size=5, root='41 0 R')
    asset = 'assets/pdf/standalone-catalog-size.pdf'
    data = bytes(pdf.data)
    row = {'asset': asset, 'width': 24, 'height': 16,
           'rgba_zlib': base64.b64encode(zlib.compress(bytes((255, 0, 0, 255)) * (24 * 16), 9)).decode(),
           'tolerance': 0,
           'provenance': 'Literal red page for an owned standalone table with an undersized catalog bound.'}
    path = ROOT / asset
    reference = ROOT / 'tests/fixtures/pdf-image-reference.json'
    records = json.loads(reference.read_text())
    index = next((i for i, item in enumerate(records['cases']) if item['asset'] == asset), None)
    if '--check' in sys.argv:
        assert path.read_bytes() == data
        assert index is not None and records['cases'][index] == row
    else:
        path.write_bytes(data)
        if index is None:
            records['cases'].append(row)
        else:
            records['cases'][index] = row
        reference.write_text(json.dumps(records, indent=2) + '\n')
    print('Standalone catalog-size fixture: generated bytes verified')
