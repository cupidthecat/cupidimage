#!/usr/bin/env python3
"""Build the owned Type 1 blue-zone/composite page sample."""
import argparse
from pathlib import Path
from test_pdf_type1_page_hinting import pdf

CONTENT = '''
BT /Label 14 Tf 12 158 Td (Native Type 1 hinting) Tj ET
BT /Label 9 Tf 12 141 Td (Enable --pdf-type1-hinting and --pdf-text-aa.) Tj ET
0.15 0.3 0.8 rg BT /F 12 Tf 12.1875 112.1875 Td (ABAB) Tj ET
0.8 0.2 0.1 rg BT /F 18 Tf 12.375 76.375 Td (ABAB) Tj ET
0.1 0.5 0.2 rg BT /F 18 Tf 1 .25 -.125 1 20 37 Tm (ABAB) Tj ET
0 0 0 rg BT /Label 9 Tf 12 14 Td (Blue zones, composite accents, and PDF spacing.) Tj ET
'''
PAGE = b'''<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 240 180]
/Resources << /Font << /F 5 0 R /Label 11 0 R >> >> >>'''
LABEL = b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'


def build():
    return pdf(CONTENT, extra={3: PAGE, 11: LABEL})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / 'assets/pdf/native-type1-hinting.pdf'
    data = build()
    if args.check:
        assert path.read_bytes() == data, 'Regenerate the Type 1 page hinting fixture'
        print('PDF Type 1 hinting fixture: generated bytes verified')
    else:
        path.write_bytes(data)
        print('Wrote assets/pdf/native-type1-hinting.pdf')


if __name__ == '__main__':
    main()
