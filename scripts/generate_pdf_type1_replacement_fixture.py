#!/usr/bin/env python3
"""Build an owned page comparing long Type 1 hint traces and literal outline controls."""

import argparse
from pathlib import Path
from pdf_type1_replacement_fixture import program
from test_pdf_pages import document
from test_pdf_type3 import stream

CASES = [
    ((25, 4, False), "100 horizontal declarations"),
    ((32, 4, True), "128 vertical declarations"),
    ((8, 16, False), "16 replacement groups"),
    ((8, 32, True), "32 replacement groups"),
    ((10, 32, False), "320 declarations"),
    ((97, 1, False), "97 simultaneously active hints"),
]


def build(controls=False):
    objects = {8: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"}

    def font(number, variant, control=False):
        data, clear, encrypted = program(*variant, hints=not control)
        objects[number] = (
            f"<< /Type /Font /Subtype /Type1 /BaseFont /CupidShapes /Encoding /WinAnsiEncoding /FirstChar 65 /LastChar 65 /Widths [600] /FontDescriptor {number+1} 0 R >>".encode()
        )
        objects[number + 1] = (
            f"<< /Type /FontDescriptor /FontName /CupidShapes /Flags 32 /FontBBox [0 -200 1000 1000] /Ascent 800 /Descent -200 /ItalicAngle 0 /CapHeight 600 /StemV 80 /FontFile {number+2} 0 R >>".encode()
        )
        objects[number + 2] = stream(data, f"/Length1 {clear} /Length2 {encrypted} /Length3 0")

    names = ["/Label 8 0 R"]
    content = [
        "BT /Label 16 Tf 18 278 Td (Type 1 hint replacement traces) Tj ET",
        "BT /Label 9 Tf 18 261 Td (Each pair uses the same outline and fitting fallback.) Tj ET",
        "BT /Label 10 Tf 24 239 Td (Control) Tj ET",
        "BT /Label 10 Tf 80 239 Td (Hint trace) Tj ET",
        "BT /Label 10 Tf 275 239 Td (Font program) Tj ET",
    ]
    for i, (variant, label) in enumerate(CASES):
        number = 10 + i * 6
        font(number, variant, controls)
        font(number + 3, variant, True)
        names.extend((f"/Scope{i} {number} 0 R", f"/Control{i} {number+3} 0 R"))
        y = 210 - i * 35
        content += [
            f"0 g BT /Label 9 Tf 80 {y+4} Td ({label}) Tj ET",
            f"0.1 0.25 0.65 rg BT /Control{i} 24 Tf 24 {y} Td (AAA) Tj ET",
            f"BT /Scope{i} 24 Tf 275 {y} Td (AAA) Tj ET",
        ]
    return document(
        "/MediaBox [0 0 420 300] /Resources << /Font << " + " ".join(names) + " >> >>",
        "",
        " ".join(content),
        objects,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "assets/pdf/type1-hint-replacements.pdf"
    if args.check:
        assert path.read_bytes() == build(), "Regenerate the Type 1 hint-replacement sample"
        print("Type 1 hint-replacement sample: generated bytes verified")
    else:
        path.write_bytes(build())
