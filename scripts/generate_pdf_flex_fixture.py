#!/usr/bin/env python3
"""Build owned flex and literal-curve glyphs at several page sizes."""

import argparse
from pathlib import Path
from test_pdf_cff import fixture as font_fixture
from test_pdf_cff_render import fixture as page_fixture
from test_pdf_type2 import command


def build():
    move = command([0, 700], 21)
    deltas = [100, 0, 100, 12, 100, 0, 100, 0, 100, -12, 100, 0]
    finish = command([0, -700, -600, 0, 0, 700], 5) + b"\x0e"
    font = font_fixture(
        programs=[
            b"\x0e",
            b"\x0e",
            move + command(deltas + [50], (12, 35)) + finish,
            move + command(deltas, 8) + finish,
        ]
    )
    content = [
        "BT /Label 14 Tf 12 382 Td (CFF flex and literal curves) Tj ET",
        "BT /Label 9 Tf 12 365 Td (Use --pdf-cff-hinting with --pdf-text-aa.) Tj ET",
    ]
    for size, y in ((12, 330), (24, 280), (48, 205), (96, 85)):
        content += [
            f"BT /Label 9 Tf 12 {y-15} Td ({size} pt: flex at left, literal curves at right) Tj ET",
            f"0.1 0.25 0.65 rg BT /F {size} Tf 12 {y} Td (A) Tj ET",
            f"0.65 0.2 0.1 rg BT /F {size} Tf 160 {y} Td (B) Tj ET",
        ]
    page = b"<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 300 400] /Resources << /Font << /F 5 0 R /Label 11 0 R >> >> >>"
    return page_fixture(
        " ".join(content),
        font=font,
        encoding="<< /BaseEncoding /WinAnsiEncoding /Differences [65 /A /customShape] >>",
        metrics="/FirstChar 65 /LastChar 66 /Widths [600 600]",
        extra={3: page, 11: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"},
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "assets/pdf/native-cff-flex.pdf"
    if args.check:
        assert target.read_bytes() == build(), "Regenerate the CFF flex sample"
        print("PDF CFF flex fixture: generated bytes verified")
    else:
        target.write_bytes(build())
