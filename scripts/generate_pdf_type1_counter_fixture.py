#!/usr/bin/env python3
"""Generate an owned two-stem Type 1 counter-data regression fixture."""
import argparse
import hashlib
from pathlib import Path
from test_pdf_type1_counters import counter
from test_pdf_type1_charstrings import command, WIDTH
from test_pdf_type1_render import fixture


def make():
    shape = b''
    for y in (0, 580):
        # closepath retains the logical endpoint at (0, y + 20).
        shape += command([0, y if not shape else 560], 21)
        shape += command([400, 0], 5)+command([0, 20], 5)+command([-400, 0], 5)+b'\x09'
    code = WIDTH+counter([1, 0, 20, 580, -20, 0], chunk=3)
    code += command([0, 20], 1)+command([580, 20], 1)+shape+b'\x0e'
    return fixture('BT /F 36 Tf 16 28 Td (AA) Tj ET',
                   glyphs=[('.notdef', WIDTH+b'\x0e'), ('A', code)])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1]/'assets/pdf/type1-counter-hints.pdf'
    data = make()
    if args.check:
        assert path.read_bytes() == data, 'Type 1 counter fixture is stale'
        print('Type 1 counter fixture: generated bytes verified')
    else:
        path.write_bytes(data)
        print(hashlib.sha256(data).hexdigest())


if __name__ == '__main__':
    main()
