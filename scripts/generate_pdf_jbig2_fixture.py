#!/usr/bin/env python3
"""Build the owned JBIG2 sample page from stored encoded bitmap controls."""

import argparse
import base64
import json
from pathlib import Path
from test_pdf_pages import document
from test_pdf_images import image_stream

ROOT = Path(__file__).resolve().parents[1]


def build(raw=False):
    fixtures = json.loads((ROOT / "tests/fixtures/pdf-jbig2.json").read_text())
    objects = {7: "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"}
    globals_data = base64.b64decode(fixtures["globals"])
    objects[20] = (
        f"<< /Length {len(globals_data)} >>\nstream\n".encode() + globals_data + b"\nendstream"
    )
    content = ["BT /Label 16 Tf 12 248 Td (JBIG2 bitmap and symbol coding) Tj ET"]
    names = []
    for i, sample in enumerate(fixtures["samples"]):
        x, y = 12 + (i % 2) * 150, 142 - (i // 2) * 120
        content.append(f"BT /Label 10 Tf {x} {y+87} Td ({sample['name']}) Tj ET")
        content.append(f"q 126 0 0 78 {x} {y} cm /Im{i} Do Q")
        attrs = f"/Width {sample['width']} /Height {sample['height']} /BitsPerComponent 1 /ColorSpace /DeviceGray"
        if raw:
            data = bytes(v ^ 255 for v in base64.b64decode(sample["black_samples"]))
        else:
            data = base64.b64decode(sample["data"])
            attrs += " /Filter /JBIG2Decode"
            if sample["globals"]:
                attrs += " /DecodeParms << /JBIG2Globals 20 0 R >>"
        objects[10 + i] = image_stream(data, attrs)
        names.append(f"/Im{i} {10+i} 0 R")
    resources = "/Resources << /Font << /Label 7 0 R >> /XObject << " + " ".join(names) + " >> >>"
    return document("/MediaBox [0 0 300 270] " + resources, "", " ".join(content), objects)


def vectors():
    fixtures = json.loads((ROOT / "tests/fixtures/pdf-jbig2.json").read_text())
    lines = ["/* Generated owned JBIG2 streams and exact PDF sample controls. */"]
    data = [("globals", base64.b64decode(fixtures["globals"]))]
    for i, sample in enumerate(fixtures["samples"]):
        data.append((f"data_{i}", base64.b64decode(sample["data"])))
        data.append(
            (f"samples_{i}", bytes(v ^ 255 for v in base64.b64decode(sample["black_samples"])))
        )
    for name, value in data:
        lines.append(f"static const unsigned char jb2_{name}[] = {{")
        for start in range(0, len(value), 16):
            lines.append("    " + ", ".join(f"0x{b:02x}" for b in value[start : start + 16]) + ",")
        lines.append("};")
    lines.append(
        "static const struct { const unsigned char *data, *globals, *samples; size_t length, globals_length; uint32_t width, height; } jb2_fixtures[] = {"
    )
    for i, sample in enumerate(fixtures["samples"]):
        globals_fields = "jb2_globals, " if sample["globals"] else "NULL, "
        globals_size = "sizeof(jb2_globals)" if sample["globals"] else "0"
        lines.append(
            f"    {{jb2_data_{i}, "
            + globals_fields
            + f"jb2_samples_{i}, sizeof(jb2_data_{i}), {globals_size}, {sample['width']}, {sample['height']}}},"
        )
    lines.append("};")
    return ("\n".join(lines) + "\n").encode()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "assets/pdf/native-jbig2.pdf"
    vector_target = ROOT / "tests/fixtures/pdf-jbig2.inc"
    if args.check:
        assert vector_target.read_bytes() == vectors(), "Regenerate the JBIG2 core vectors"
        assert target.read_bytes() == build(), "Regenerate the JBIG2 sample page"
        print("JBIG2 sample page: generated bytes verified")
    else:
        target.write_bytes(build())
        vector_target.write_bytes(vectors())
