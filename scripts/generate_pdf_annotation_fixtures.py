#!/usr/bin/env python3
"""Build owned normal-appearance and widget-state PDF fixtures."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_annotation_pages import page
from test_pdf_forms import form


def fixtures():
    normal = page()
    widget = page('<< /Subtype /Widget /Rect [3 1.5 9 10.5] /AS /On /AP << /N << /Off 21 0 R /On 20 0 R >> >> >>',
                  extra={21: form('1 0 0 rg 0 0 6 9 re f', '/BBox [0 0 6 9]')})
    return {'assets/pdf/reference/annotation-appearance.pdf': normal,
            'assets/pdf/reference/annotation-widget-state.pdf': widget}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    reference = root / 'tests/fixtures/pdf-image-reference.json'
    data = json.loads(reference.read_text())
    pixels = bytes(c for y in range(16) for x in range(24) for c in
                   ((0, 128, 255, 255) if 4 <= x < 12 and 2 <= y < 14 else (255,) * 4))
    for name, pdf in fixtures().items():
        path = root / name
        row = {'asset': name, 'width': 24, 'height': 16,
               'rgba_zlib': base64.b64encode(zlib.compress(pixels, 9)).decode(), 'tolerance': 0,
               'provenance': 'Literal pixel rectangle selected from a normal appearance and mapped from its BBox to Rect.'}
        index = next((i for i, case in enumerate(data['cases']) if case['asset'] == name), None)
        if args.check:
            assert path.read_bytes() == pdf, 'Regenerate ' + name
            assert index is not None and data['cases'][index] == row, 'Regenerate annotation references'
        else:
            path.write_bytes(pdf)
            if index is None:
                data['cases'].append(row)
            else:
                data['cases'][index] = row
    if not args.check:
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF annotation fixtures: generated bytes verified' if args.check else 'Wrote PDF annotation fixtures')


if __name__ == '__main__':
    main()
