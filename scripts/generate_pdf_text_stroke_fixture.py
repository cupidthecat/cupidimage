#!/usr/bin/env python3
"""Build the owned text-stroke regression page; --check verifies its bytes."""
import argparse
from pathlib import Path
from test_pdf_embedded_fonts import fixture

CONTENT = '''
BT /Label 12 Tf 12 166 Td (Text stroke coverage) Tj ET
BT /Label 8 Tf 12 152 Td (Use --pdf-text-aa to compare stroke edges.) Tj ET
0.15 0.3 0.8 RG .75 w BT /F 27 Tf 1 Tr 12.1875 112.1875 Td (ACFG) Tj ET
0.8 0.2 0.1 RG 1.5 w 1 j BT /F 20 Tf 1 Tr 1 .25 -.125 1 145 105 Tm (AC) Tj ET
q 0.3 0.6 0.2 rg 0.2 0.1 0.6 RG /Opacity gs 1.125 w
BT /F 27 Tf 2 Tr 12.375 70.375 Td (ACFG) Tj ET Q
0.15 0.3 0.8 RG 12 w BT /F 12 Tf 1 Tr 176 65 Td (A) Tj ET
.75 w 1 J [0 2] 0 d BT /F 24 Tf 1 Tr 12 30 Td (AC) Tj ET
2 J [0 2] 0 d BT /F 24 Tf 1 Tr 100 30 Td (AC) Tj ET
[] 0 d 0 0 0 rg BT /Label 8 Tf 0 Tr 12 10 Td (Round and square zero-length dashes; wide stroke at right.) Tj ET
'''
PAGE = b'''<< /Type /Page /Parent 2 0 R /Contents 4 0 R
/MediaBox [0 0 240 180] /Resources << /Font << /F 5 0 R /Label 11 0 R >>
/ExtGState << /Opacity 12 0 R >> >> >>'''

def build():
    return fixture(CONTENT, extra={3:PAGE,
        11:b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        12:b'<< /ca .6 /CA .4 >>'})

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/text-strokes.pdf'
    data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the text-stroke sample'
        print('PDF text stroke fixture: generated bytes verified')
    else:
        path.write_bytes(data)
        print(f'Wrote {path.name}')

if __name__=='__main__':
    main()
