#!/usr/bin/env python3
"""Build the owned calibrated/ICC blending and luminosity page."""
import argparse
from pathlib import Path
from test_pdf_pages import document
from test_pdf_forms import form
from test_pdf_type3 import stream
from test_pdf_icc import profile,gamma
from test_pdf_calibrated import D65

def build():
    icc='[/ICCBased 100 0 R]'
    matrix='.636958 .2627002 0 .1446169 .6779981 .0280727 .1688809 .0593017 1.0609851'
    wide='[/CalRGB << /WhitePoint ['+D65+'] /Matrix ['+matrix+'] >>]'
    source='[/CalRGB << /WhitePoint ['+D65+'] /Matrix ['+matrix+'] /Gamma [2 2 2] >>]'
    box='/BBox [0 0 144 60]'
    half='/ExtGState << /Half 30 0 R >>'
    objects={
        5:'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        20:form('0 g 0 0 144 60 re f /Half gs 1 g 0 0 144 60 re f',
                box+' /Group << /S /Transparency /I true /CS /DeviceRGB >> /Resources << '+half+' >>'),
        21:form('/C cs 0 scn 0 0 144 60 re f /Half gs 1 scn 0 0 144 60 re f',
                box+' /Group << /S /Transparency /I true /CS '+icc+' >> /Resources << /ColorSpace << /C '+icc+' >> '+half+' >>'),
        22:form('/C cs 0 0 0 scn 0 0 144 60 re f /Half gs /Source cs 0 1 0 scn 0 0 144 60 re f',
                box+' /Group << /S /Transparency /I true /CS '+wide+' >> /Resources << /ColorSpace << /C '+wide+' /Source '+source+' >> '+half+' >>'),
        23:form('/Mask gs .15 .3 .8 rg 0 0 144 60 re f',
                box+' /Resources << /ExtGState << /Mask 31 0 R >> >>'),
        24:form('/C cs .5 scn 0 0 144 60 re f',
                box+' /Group << /S /Transparency /I true /CS '+icc+' >> /Resources << /ColorSpace << /C '+icc+' >> >>'),
        30:'<< /ca .5 >>',31:'<< /SMask << /S /Luminosity /G 24 0 R >> >>',
        100:stream(profile([gamma(2)],gray=True),'/N 1')}
    body='''
BT /Label 14 Tf 12 220 Td (Blending in calibrated color spaces) Tj ET
BT /Label 9 Tf 12 199 Td (Device RGB blend) Tj 180 0 Td (ICC gray, gamma 2) Tj ET
q 1 0 0 1 12 132 cm /RGB Do Q
q 1 0 0 1 192 132 cm /ICC Do Q
BT /Label 9 Tf 12 107 Td (Wide-gamut group) Tj 180 0 Td (CIE luminosity soft mask) Tj ET
q 1 0 0 1 12 40 cm /Wide Do Q
q 1 0 0 1 192 40 cm /Mask Do Q
BT /Label 8 Tf 12 19 Td (Top: half-white over black. Bottom: gamut retention and a 25-percent luminosity mask.) Tj ET
'''
    return document('/MediaBox [0 0 360 240] /Resources << /Font << /Label 5 0 R >> /XObject << /RGB 20 0 R /ICC 21 0 R /Wide 22 0 R /Mask 23 0 R >> >>',stream=body,extra=objects)

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/cie-blending.pdf';data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the CIE blending fixture'
        print('PDF CIE blending fixture: generated bytes verified')
    else:
        path.write_bytes(data);print(f'Wrote {path.name}')
if __name__=='__main__':main()
