#!/usr/bin/env python3
"""Build owned optional-content state and text-visibility fixtures."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_pages import document
from test_pdf_optional_pages import page, CATALOG, GROUPS


def fixtures():
    objects = {1: CATALOG, **GROUPS,
               20: '<< /Type /OCMD /OCGs [91 0 R] /P /AnyOff >>',
               21: '<< /Type /OCMD /VE [/And 90 0 R [/Not 91 0 R]] >>'}
    objects[91] = '<< /Type /OCG /Name (on) >>'
    resources = '/Properties << /On 90 0 R /Off 91 0 R /P 20 0 R /V 21 0 R >>'
    content = ('/OC /Off BDC 1 0 1 rg 0 0 18 12 re f EMC '
               '/OC /On BDC 0 1 0 rg 0 0 6 12 re f EMC '
               '/OC /P BDC 0 0 1 rg 6 0 6 12 re f EMC '
               '/OC /V BDC 1 0 0 rg 12 0 6 12 re f EMC')
    state = document('/MediaBox [0 0 18 12] /Resources << ' + resources + ' >>',
                     stream=content, extra=objects).replace(b'%PDF-1.4', b'%PDF-1.7', 1)
    text = page('BT /F 12 Tf 12 72 Td (Visible text) Tj ET '
                'BT /F 12 Tf 12 52 Td /OC /Off BDC (Hidden ) Tj EMC (advance kept) Tj ET '
                'q /OC /Off BDC BT /F 24 Tf 12 22 Td 7 Tr (CLIP) Tj ET EMC '
                '0 .4 1 rg 0 0 180 90 re f Q '
                'BT /F 8 Tf 12 8 Td (Hidden glyphs retain clipping) Tj ET', size=(180, 90))
    return {'assets/pdf/reference/optional-content-state.pdf': state,
            'assets/pdf/optional-content-text.pdf': text}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    for name, data in fixtures().items():
        path = root / name
        if args.check:
            assert path.read_bytes() == data, 'Regenerate ' + name
        else:
            path.write_bytes(data)
    reference = root / 'tests/fixtures/pdf-image-reference.json'
    data = json.loads(reference.read_text())
    row_pixels = bytes((0, 255, 0, 255)) * 8 + bytes((0, 0, 255, 255)) * 8 + bytes((255, 0, 0, 255)) * 8
    row = {'asset': 'assets/pdf/reference/optional-content-state.pdf', 'width': 24, 'height': 16,
           'rgba_zlib': base64.b64encode(zlib.compress(row_pixels * 16, 9)).decode(), 'tolerance': 0,
           'provenance': 'Literal RGB bands selected by default OCG states, an OCMD policy and a visibility expression.'}
    index = next((i for i, case in enumerate(data['cases']) if case['asset'] == row['asset']), None)
    if args.check:
        assert index is not None and data['cases'][index] == row, 'Regenerate the optional-content reference'
    else:
        if index is None:
            data['cases'].append(row)
        else:
            data['cases'][index] = row
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF optional-content fixtures: generated bytes verified' if args.check else 'Wrote PDF optional-content fixtures')


if __name__ == '__main__':
    main()
