#!/usr/bin/env python3
"""Build an owned PDF with recoverable scalar and Type 1 boundary errors."""

import argparse
from pathlib import Path
from test_pdf_font_boundaries import fixture
from test_pdf_type1 import fixture as font_program
from test_pdf_type1_charstrings import WIDTH, BOX


def build():
    raw, clear, encrypted = font_program(glyphs=[(".notdef", WIDTH + b"\x0e"), ("A", BOX)])
    return fixture(raw, (clear - 5, encrypted, 0), joined=(10, 11, 12), compressed=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path("assets/pdf/recovered-font-streams.pdf")
    data = build()
    if args.check:
        assert path.read_bytes() == data, "Regenerate recovered font-stream fixture"
        print("Recovered font streams: generated bytes verified")
    else:
        path.write_bytes(data)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
