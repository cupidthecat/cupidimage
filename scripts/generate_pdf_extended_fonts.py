#!/usr/bin/env python3
"""Embed pinned, unmodified extended substitute fonts as bounded zlib streams."""
import hashlib
import json
from pathlib import Path
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/extended-standard-fonts'
FONTS = {}
for family, substitute in (('Courier', 'Mono'), ('Helvetica', 'Sans'), ('Times', 'Serif')):
    for style in ('Regular', 'Bold', 'Italic', 'BoldItalic'):
        suffix = style if family == 'Times' else style.replace('Italic', 'Oblique')
        name = (family + ('-Roman' if family == 'Times' else '') if style == 'Regular'
                else family + '-' + suffix)
        FONTS[name] = 'Liberation' + substitute + '-' + style + '.ttf'


def generate():
    for row in json.loads((SOURCE / 'manifest.json').read_text())['files']:
        assert hashlib.sha256((SOURCE / row['file']).read_bytes()).hexdigest() == row['sha256']
    lines = ['/* Generated by scripts/generate_pdf_extended_fonts.py.',
             ' * Original font bytes are preserved by lossless compression.',
             ' * Copyright 2010 Google Corporation; Copyright 2012 Red Hat, Inc.',
             ' * SIL Open Font License 1.1: third_party/extended-standard-fonts/LICENSE.',
             ' * Include THIRD_PARTY_NOTICES.md with binary distributions. */']
    entries = []
    for i, (name, filename) in enumerate(sorted(FONTS.items())):
        raw = (SOURCE / filename).read_bytes()
        data = zlib.compress(raw, 9)
        lines.append(f'static const unsigned char extended_font_{i}[] = {{')
        lines.extend('    ' + ','.join(f'0x{v:02x}' for v in data[j:j+20]) + ','
                     for j in range(0, len(data), 20))
        lines.append('};')
        entries.append(f'    {{"{name}", extended_font_{i}, sizeof(extended_font_{i}), {len(raw)}}},')
    lines += ['static const pdf_extended_font extended_fonts[] = {', *entries, '};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    target = ROOT / 'src/formats/pdf/fonts/extended_outlines.inc'
    value = generate()
    if '--check' in sys.argv:
        assert target.read_text() == value, 'Regenerate extended font outlines'
    else:
        target.write_text(value)
