#!/usr/bin/env python3
"""Embed renamed spacing-mark subsets without changing their glyph geometry."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/standard-spacing-marks'
TARGET = ROOT / 'src/formats/pdf/fonts/standard_marks.inc'


def rebuild(source_directory, manifest):
    from io import BytesIO
    import fontTools
    from fontTools import subset
    from fontTools.ttLib import TTFont
    from fontTools.pens.recordingPen import RecordingPen

    assert fontTools.__version__ == manifest['fonttools_version'], 'Use the recorded generator version'
    for row in manifest['fonts']:
        path = source_directory / row['original_file']
        assert hashlib.sha256(path.read_bytes()).hexdigest() == row['original_sha256'], path
        with TTFont(path) as font:
            before = RecordingPen()
            font.getGlyphSet()['space_uni0326'].draw(before)
            width = font['hmtx']['space_uni0326'][0]
            options = subset.Options()
            options.notdef_outline = True
            options.glyph_names = True
            selection = subset.Subsetter(options=options)
            selection.populate(glyphs=['space_uni0326'])
            selection.subset(font)
            cff = font['CFF '].cff
            top = cff.topDictIndex[0]
            assert top.charset == ['.notdef', 'space_uni0326']
            cff.fontNames[0] = row['subset_name']
            top.FullName = row['subset_name']
            top.FamilyName = 'CupidImage Spacing Marks'
            top.Notice += (' Derived spacing-mark subset for CupidImage; glyph set and font names '
                           'changed. See third_party/standard-spacing-marks/README.md.')
            after = RecordingPen()
            font.getGlyphSet()['space_uni0326'].draw(after)
            assert before.value == after.value and font['hmtx']['space_uni0326'][0] == width
            data = BytesIO()
            cff.compile(data, font)
            raw = data.getvalue()
            assert hashlib.sha256(raw).hexdigest() == row['subset_sha256'], row['file']
            (SOURCE / row['file']).write_bytes(raw)


def generate(manifest):
    for row in manifest['notices']:
        assert hashlib.sha256((SOURCE / row['file']).read_bytes()).hexdigest() == row['sha256'], row['file']
    lines = [
        '/* Generated by scripts/generate_pdf_standard_marks.py.',
        ' * Renamed spacing-mark subsets of TeX Gyre Cursor/Termes 2.004.',
        ' * Original glyph geometry is retained; glyph sets and font names are changed.',
        ' * Copyright 2006-2009 B. Jackowski and J.M. Nowacki (TeX users groups).',
        ' * GUST Font License / LPPL 1.3c: third_party/standard-spacing-marks.',
        ' * Include THIRD_PARTY_NOTICES.md and the documented font source with distributions. */',
    ]
    entries = []
    for i, row in enumerate(manifest['fonts']):
        raw = (SOURCE / row['file']).read_bytes()
        assert hashlib.sha256(raw).hexdigest() == row['subset_sha256'], row['file']
        lines.append(f'static const unsigned char standard_mark_{i}[] = {{')
        lines.extend('    ' + ','.join(f'0x{value:02x}' for value in raw[j:j+20]) + ','
                     for j in range(0, len(raw), 20))
        lines.append('};')
        entries.append(f'    {{"{row["standard_name"]}", standard_mark_{i}, sizeof(standard_mark_{i})}},')
    lines += ['static const pdf_standard_outline standard_marks[] = {', *entries, '};', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--rebuild', type=Path, help='Directory containing the pinned original OTFs')
    options = parser.parse_args()
    manifest = json.loads((SOURCE / 'manifest.json').read_text())
    if options.rebuild:
        rebuild(options.rebuild, manifest)
    value = generate(manifest)
    if options.check:
        assert TARGET.read_text() == value, 'Regenerate standard spacing marks'
    else:
        TARGET.write_text(value)


if __name__ == '__main__':
    main()
