#!/usr/bin/env python3
"""Materialize owned empty-user-password assets from pinned independent fixtures."""

import base64
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]


def main():
    fixture = json.loads(
        (ROOT / "tests/fixtures/pdf-security-structure-reference.json").read_text()
    )
    for case in fixture["public_assets"]:
        data = base64.b64decode(case["document"])
        assert hashlib.sha256(data).hexdigest() == case["sha256"]
        path = ROOT / case["path"]
        assert path.parent == ROOT / "assets/pdf"
        if "--check" in sys.argv:
            assert path.read_bytes() == data, case["path"]
        else:
            path.write_bytes(data)
    print(f'PDF security assets: {len(fixture["public_assets"])} generated bytes verified')


if __name__ == "__main__":
    main()
