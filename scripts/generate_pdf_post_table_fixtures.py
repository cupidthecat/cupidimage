#!/usr/bin/env python3
"""Build owned samples for legacy character-code and high-index glyph names."""
from pathlib import Path
import sys
from test_pdf_post_tables import named_font, page

ROOT = Path(__file__).resolve().parents[1]


def fixtures():
    for kind, title in (('aat4', 'Legacy character-code glyph names'),
                        ('high-index', 'Full-range custom glyph names')):
        font, names = named_font(kind)
        content = (f'BT /Label 12 Tf 16 158 Td ({title}) Tj ET '
                   '.2 .4 .8 rg BT /F 36 Tf 20 102 Td [(A) -1000 (B)] TJ ET '
                   '.8 .2 .1 RG 1 w BT /F 36 Tf 1 Tr 20 42 Td [(A) -1000 (B)] TJ ET')
        extra = {3: '<< /Type /Page /Parent 2 0 R /MediaBox [0 0 240 180] /Contents 4 0 R '
                    '/Resources << /Font << /F 5 0 R /Label 15 0 R >> >> >>',
                 15: '<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'}
        yield 'post-' + kind + '-names.pdf', page(content, font, names, extra)


if __name__ == '__main__':
    for name, data in fixtures():
        path = ROOT / 'assets/pdf' / name
        if '--check' in sys.argv:
            assert path.read_bytes() == data, 'Regenerate ' + name
        else:
            path.write_bytes(data)
    print('PDF post-name fixtures: generated bytes verified')
