#!/usr/bin/env python3
"""Build owned direct-GID CFF descendant fixtures."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_cff_bindings import fixture


def fixtures():
    page = '<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 18 12] /Resources << /Font << /F 5 0 R >> >> >>'
    content = '0 .5 1 rg BT /F 15 Tf 1.875 1.5 Td <0002> Tj ET'
    return {'assets/pdf/reference/cff-direct-cid.pdf': fixture(content, extra={3: page}),
            'assets/pdf/reference/opentype-cff-direct-cid.pdf': fixture(content, True, extra={3: page})}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    reference = root / 'tests/fixtures/pdf-image-reference.json'
    data = json.loads(reference.read_text())
    pixels = bytes(c for y in range(16) for x in range(24) for c in
                   ((0, 128, 255, 255) if 4 <= x < 12 and 2 <= y < 14 else (255,) * 4))
    for name, pdf in fixtures().items():
        path = root / name
        row = {'asset': name, 'width': 24, 'height': 16,
               'rgba_zlib': base64.b64encode(zlib.compress(pixels, 9)).decode(), 'tolerance': 0,
               'provenance': 'Literal blue rectangle selected by CID 2 as CharStrings index 2 in a name-keyed CFF descendant.'}
        index = next((i for i, case in enumerate(data['cases']) if case['asset'] == name), None)
        if args.check:
            assert path.read_bytes() == pdf, 'Regenerate ' + name
            assert index is not None and data['cases'][index] == row, 'Regenerate CFF binding references'
        else:
            path.write_bytes(pdf)
            if index is None:
                data['cases'].append(row)
            else:
                data['cases'][index] = row
    if not args.check:
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF CFF binding fixtures: generated bytes verified' if args.check else 'Wrote PDF CFF binding fixtures')


if __name__ == '__main__':
    main()
