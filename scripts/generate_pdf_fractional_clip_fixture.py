#!/usr/bin/env python3
"""Build the owned fractional-clipping sample; --check verifies its bytes."""
import argparse
from pathlib import Path
from test_pdf_embedded_fonts import fixture
from test_pdf_forms import form

CONTENT = '''
0 0 0 rg BT /Label 12 Tf 12 166 Td (Fractional clipping) Tj ET
BT /Label 8 Tf 12 152 Td (Use --pdf-text-aa for text and clipping edges.) Tj ET
q BT /F 40 Tf 7 Tr 12.1875 105.1875 Td (ACG) Tj ET
0.1 0.3 0.9 rg 0 0 240 180 re f
0.6 0.8 1 rg 0 112 240 2 re f 0 120 240 2 re f Q
q 12.1875 63.1875 40 23 re W n
0.2 0.65 0.3 rg 0.15 0.2 0.8 RG 1.125 w
BT /F 32 Tf 2 Tr 12.1875 63.1875 Td (ACG) Tj ET Q
q /Opacity gs 1 0 0 1 145.1875 63.1875 cm /G Do Q
0 0 0 rg BT /Label 8 Tf 12 48 Td (Nested clip) Tj 126 0 Td (Form boundary) Tj ET
'''
for index in range(40):
    x=12.1875+index*4.125
    clip=f'{x} 22.1875 .1875 16 re W n '
    CONTENT+='q '+clip+clip+'0.1 0.3 0.9 rg 0 0 240 180 re f Q\n'
CONTENT+='0 0 0 rg BT /Label 8 Tf 12 10 Td (Repeated clips keep the same edge coverage.) Tj ET\n'
PAGE = b'''<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 240 180]
/Resources << /Font << /F 5 0 R /Label 11 0 R >> /XObject << /G 12 0 R >>
/ExtGState << /Opacity 13 0 R >> >> >>'''


def build():
    return fixture(CONTENT,extra={3:PAGE,
        11:b'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
        12:form('0.8 0.2 0.1 rg BT /F 40 Tf 0 Tr 0 0 Td (C) Tj ET',
                '/BBox [0 0 10.1875 25.1875] /Resources << /Font << /F 5 0 R >> >> '
                '/Group << /S /Transparency /I true /CS /DeviceRGB >>'),
        13:b'<< /ca .6 /CA .6 >>'})


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/fractional-clipping.pdf'
    data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the fractional-clipping sample'
        print('PDF fractional clipping fixture: generated bytes verified')
    else:
        path.write_bytes(data)
        print(f'Wrote {path.name}')


if __name__=='__main__':
    main()
