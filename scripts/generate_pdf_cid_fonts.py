#!/usr/bin/env python3
"""Pack unmodified, pinned CID substitute fonts into bounded C string rows."""
import hashlib
import json
from pathlib import Path
import sys
import zlib

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/cid-standard-fonts'
OUTPUT = ROOT / 'src/formats/pdf/fonts/substitute'
ROW_BYTES = 4094


def generate(row):
    raw = (SOURCE / row['file']).read_bytes()
    assert len(raw) == row['size']
    assert hashlib.sha256(raw).hexdigest() == row['sha256'], row['file']
    packed = zlib.compress(raw, 9)
    lines = ['/* Generated by scripts/generate_pdf_cid_fonts.py.',
             ' * Unmodified Harano Aji font bytes, compressed without loss.',
             ' * ' + row['copyright'],
             ' * SIL Open Font License 1.1: third_party/cid-standard-fonts/LICENSE.',
             ' * Include THIRD_PARTY_NOTICES.md with binary distributions. */',
             '#include "cid_data.h"',
             f'static const unsigned char cid_data[][{ROW_BYTES}] = {{']
    # Each initializer fits the C99 minimum supported string-literal length.
    # Fixed-size rows are contiguous; only the final row has unused padding.
    for start in range(0, len(packed), ROW_BYTES):
        block = packed[start:start + ROW_BYTES]
        for at in range(0, len(block), 20):
            line = '    "' + ''.join(f'\\x{byte:02x}' for byte in block[at:at + 20]) + '"'
            lines.append(line + (',' if at + 20 >= len(block) else ''))
    lines += ['};', f'const pdf_cid_font_source cupidimage_pdf_cid_{row["face"]} = {{',
              f'    "{row["file"]}", "{row["registry"]}", "{row["ordering"]}", {row["supplement"]},',
              f'    (const unsigned char *)cid_data, {len(packed)}, {len(raw)}', '};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    for row in json.loads((SOURCE / 'manifest.json').read_text())['files']:
        path = OUTPUT / ('cid_' + row['face'] + '.inc')
        data = generate(row)
        if '--check' in sys.argv:
            assert path.read_text() == data, f'Regenerate {path.name}'
        else:
            path.write_text(data)
    print('Pinned CID fonts: original bytes and packed sources verified')
