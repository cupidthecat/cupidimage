#!/usr/bin/env python3
"""Build owned, pixel-qualified PDF CID subset-recovery fixtures."""
import argparse
import base64
import json
from pathlib import Path
import zlib
from test_pdf_subset_fonts import tt_pair
from test_pdf_embedded_fonts import fixture as tt_pdf
from test_pdf_cff_render import fixture as cff_pdf, BOX, CURVE
from test_pdf_cff import fixture as cff_font


def fixtures():
    page = b'<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 18 12] /Resources << /Font << /F 5 0 R >> >> >>'
    _, broken, _ = tt_pair(True, True)
    program = '0 .5 1 rg BT /F 15 Tf 1.875 1.5 Td <0001> Tj ET'
    truetype = tt_pdf(program, cid=True, font_data=broken, extra={3: page})
    cff = cff_font(cid=True, programs=[b'\x0e', b'\x0e', BOX, CURVE],
                   fdselect=b'\3\0\1\0\1\0\0\4')
    compact = cff_pdf(program.replace('<0001>', '<0022>'), cid=True, font=cff, extra={3: page})
    return {'assets/pdf/reference/subset-cid-truetype.pdf': truetype,
            'assets/pdf/reference/subset-cid-cff.pdf': compact}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    reference = root / 'tests/fixtures/pdf-image-reference.json'
    data = json.loads(reference.read_text())
    pixels = bytes(value for y in range(16) for x in range(24) for value in
                   ((0, 128, 255, 255) if 4 <= x < 12 and 2 <= y < 14 else (255,) * 4))
    for name, pdf in fixtures().items():
        path = root / name
        row = {'asset': name, 'width': 24, 'height': 16,
               'rgba_zlib': base64.b64encode(zlib.compress(pixels, 9)).decode(), 'tolerance': 0,
               'provenance': 'Literal rectangle from an owned CID glyph, preserving its identity and outline through bounded subset recovery.'}
        index = next((i for i, case in enumerate(data['cases']) if case['asset'] == name), None)
        if args.check:
            assert path.read_bytes() == pdf, 'Regenerate ' + name
            assert index is not None and data['cases'][index] == row, 'Regenerate ' + name + ' reference'
        else:
            path.write_bytes(pdf)
            if index is None:
                data['cases'].append(row)
            else:
                data['cases'][index] = row
    if not args.check:
        reference.write_text(json.dumps(data, indent=2) + '\n')
    print('PDF subset-recovery fixtures: generated bytes verified' if args.check else 'Wrote PDF subset-recovery fixtures')


if __name__ == '__main__':
    main()
