#!/usr/bin/env python3
"""Build the owned PDF image-interpolation comparison page."""
import argparse
from pathlib import Path
from test_pdf_pages import document
from test_pdf_images import image_stream,RGB
from test_pdf_type3 import stream

def build():
    attrs='/Width 2 /Height 2 /BitsPerComponent 8 /ColorSpace /DeviceRGB'
    objects={5:'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
             6:image_stream(RGB,attrs),7:image_stream(RGB,attrs+' /Interpolate true'),
             8:image_stream(bytes((220,40,30))*4,attrs+' /Interpolate true /SMask 9 0 R'),
             9:image_stream(bytes((0,85,170,255)),'/Width 2 /Height 2 /BitsPerComponent 8 /ColorSpace /DeviceGray /Interpolate true'),
             10:'<< /Type /Font /Subtype /Type3 /FontBBox [0 0 1000 700] /FontMatrix [.001 0 0 .001 0 0] /CharProcs << /A 11 0 R >> /Encoding << /Differences [65 /A] >> /FirstChar 65 /LastChar 65 /Widths [1000] /Resources << /XObject << /Mask 12 0 R >> >> >>',
             11:stream('1000 0 0 0 1000 700 d1 1000 0 0 700 0 0 cm /Mask Do'),
             12:image_stream(b'\x40\x80','/Width 2 /Height 2 /ImageMask true /Interpolate true')}
    content='''
BT /Label 12 Tf 12 208 Td (PDF image interpolation) Tj ET
BT /Label 8 Tf 12 190 Td (Nearest samples) Tj 120 0 Td (Interpolate true) Tj ET
q 90 0 0 65 12 116 cm /Nearest Do Q
q 90 0 0 65 132 116 cm /Smooth Do Q
BT /Label 8 Tf 12 98 Td (Type 3 stencil glyph) Tj 120 0 Td (Independent soft mask) Tj ET
.15 .3 .8 rg BT /Glyph 90 Tf 12 25 Td (A) Tj ET
q 90 0 0 63 132 25 cm /Masked Do Q
0 g BT /Label 8 Tf 12 10 Td (Bilinear profile; image boundaries retain pixel-center coverage.) Tj ET
'''
    return document('/MediaBox [0 0 240 220] /Resources << /Font << /Label 5 0 R /Glyph 10 0 R >> /XObject << /Nearest 6 0 R /Smooth 7 0 R /Masked 8 0 R >> >>',stream=content,extra=objects)

def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/image-interpolation.pdf';data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the PDF image-interpolation asset'
        print('PDF image interpolation fixture: generated bytes verified')
    else:
        path.write_bytes(data);print(f'Wrote {path.name}')
if __name__=='__main__':main()
