#!/usr/bin/env python3
"""Build an owned text-positioning sample for equivalent PDF transforms."""

import argparse
from pathlib import Path
from test_pdf_geometry_precision import CHAIN, DIRECT
from test_pdf_embedded_fonts import fixture


def build():
    page = b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 120 90] /Contents 4 0 R /Resources << /Font << /F 5 0 R /Label 11 0 R >> >> >>"
    label = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"
    content = "BT /Label 8 Tf 8 78 Td (Equivalent translations) Tj ET "
    content += "0.1 0.3 0.8 rg q " + CHAIN + "BT /F 20 Tf 10 52 Td (AAAA) Tj ET Q "
    content += "0.1 0.3 0.8 rg q " + DIRECT + "BT /F 20 Tf 10 26 Td (AAAA) Tj ET Q "
    content += "0 g BT /Label 6 Tf 8 10 Td (Both rows should share their X positions.) Tj ET"
    return fixture(content, extra={3: page, 11: label})


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path("assets/pdf/geometry-precision.pdf")
    data = build()
    if args.check:
        assert path.read_bytes() == data, "Regenerate geometry precision fixture"
        print("PDF geometry precision fixture: generated bytes verified")
    else:
        path.write_bytes(data)
        print(f"Wrote {path}")


if __name__ == "__main__":
    main()
