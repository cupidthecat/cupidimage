#!/usr/bin/env python3
"""Build the owned CID zero-zone compatibility sample."""

import argparse
from pathlib import Path
from pdf_cid_zone_fixture import asset

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
path = Path(__file__).resolve().parents[1] / "assets/pdf/cid-truetype-zero-zones.pdf"
if args.check:
    assert path.read_bytes() == asset(), "Regenerate the CID zone sample"
    print("CID zone sample: generated bytes verified")
else:
    path.write_bytes(asset())
