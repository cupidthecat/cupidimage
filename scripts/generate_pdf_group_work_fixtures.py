#!/usr/bin/env python3
"""Build owned regressions for isolated-mask memory and clipped color work."""
import argparse
import base64
import json
import zlib
from pathlib import Path
from test_pdf_pages import document
from test_pdf_forms import form
from test_pdf_type3 import stream


def mask_page(size=(612,792),depth=4,space='/DeviceGray'):
    width,height=size
    objects={}
    for level in range(depth):
        n=10+level
        content=('' if level==depth-1 else '/M gs ')+f'1 g 0 0 {width} {height} re f'
        resources='' if level==depth-1 else '/Resources << /ExtGState << /M << /SMask << /S /Luminosity /G '+str(n+1)+' 0 R >> >> >> >>'
        objects[n]=form(content,f'/BBox [0 0 {width} {height}] /Group << /S /Transparency /I true /CS '+space+' >> '+resources)
    return document(f'/MediaBox [0 0 {width} {height}] /Resources << /ExtGState << /M << /SMask << /S /Luminosity /G 10 0 R >> >> >> >>',
                    stream=f'/M gs 1 0 0 rg 0 0 {width} {height} re f',extra=objects)


def clipped_color_page(repeats=16,clip=True,image=False):
    calc=stream('{ '+'dup mul '*40+'0 0 0 4 -1 roll }','/FunctionType 4 /Domain [0 1] /Range [0 1 0 1 0 1 0 1]')
    space='[/Separation /ProofInk /DeviceCMYK 6 0 R]'
    objects={6:calc,7:'<< /FunctionType 2 /Domain [0 1] /C0 [1] /C1 [1] /N 1 >>'}
    if image:
        objects[8]=stream(bytes((255,)),'/Type /XObject /Subtype /Image /Width 1 /Height 1 /ColorSpace '+space+' /BitsPerComponent 8')
        resources='/XObject << /S 8 0 R >>'
        paint='q 360 0 0 240 0 0 cm /S Do Q '
    else:
        objects[8]='<< /ShadingType 2 /ColorSpace '+space+' /Coords [0 0 360 0] /Extend [true true] /Function 7 0 R >>'
        resources='/Shading << /S 8 0 R >>';paint='/S sh '
    return document('/MediaBox [0 0 360 240] /Resources << '+resources+' >>',
                    stream=('3 3 9 6 re W n ' if clip else '')+paint*repeats,extra=objects)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    root=Path(__file__).resolve().parents[1]/'assets/pdf'
    for name,data in (('nested-mask-surfaces.pdf',mask_page()),('clipped-shading-work.pdf',clipped_color_page())):
        path=root/name
        if args.check:assert path.read_bytes()==data,'Regenerate '+name
        else:path.write_bytes(data)
    reference=root.parent.parent/'tests/fixtures/pdf-image-reference.json'
    data=json.loads(reference.read_text())
    row={'asset':'assets/pdf/nested-mask-surfaces.pdf','width':816,'height':1056,
         'rgba_zlib':base64.b64encode(zlib.compress(bytes((255,0,0,255))*(816*1056),9)).decode(),
         'tolerance':0,
         'provenance':'Opaque red after four isolated luminosity masks; literal expected pixels also matched an independent 96-DPI raster exactly.'}
    found=next((i for i,x in enumerate(data['cases']) if x['asset']==row['asset']),None)
    if args.check:
        assert found is not None and data['cases'][found]==row,'Regenerate the nested-mask reference'
    else:
        if found is None:data['cases'].append(row)
        else:data['cases'][found]=row
        reference.write_text(json.dumps(data,indent=2)+'\n')
    print('PDF group-work fixtures: generated bytes verified' if args.check else 'Wrote PDF group-work fixtures')


if __name__=='__main__':main()
