#!/usr/bin/env python3
"""Build the owned nested Type 3 group-storage sample."""

import argparse
from pathlib import Path
from pdf_sparse_groups_fixture import nested

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
path = Path(__file__).resolve().parents[1] / "assets/pdf/nested-type3-groups.pdf"
data = nested(depth=6, caption=True)
if args.check:
    assert path.read_bytes() == data, "Regenerate the nested Type 3 group sample"
    print("Nested Type 3 sample: generated bytes verified")
else:
    path.write_bytes(data)
