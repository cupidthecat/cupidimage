#!/usr/bin/env python3
"""Build the owned four-component blending and ink-conversion page."""
import argparse
from pathlib import Path
from test_pdf_pages import document
from test_pdf_forms import form
from test_pdf_type3 import stream
from test_pdf_icc_lut import profile,lut as forward_lut
from test_pdf_icc_reverse import lut
from test_pdf_intents import tags


def build():
    objects={5:'<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>',
             30:'<< /ca .5 >>',31:'<< /ca .5 /BM /Hue >>',
             32:'<< /BG << /FunctionType 2 /Domain [0 1] /C0 [0] /C1 [.25] /N 1 >> /UCR << /FunctionType 2 /Domain [0 1] /C0 [0] /C1 [.5] /N 1 >> >>',
             33:'<< /BG2 /Default /UCR2 /Default >>'}
    icc=tags(profile(forward_lut(4),inputs=4,lab=False),{b'B2A0':lut(4)})
    objects[100]=stream(icc,'/N 4')
    labels=('CMYK opacity','Hue with retained black ink','Black generation / undercolor removal','Four-component ICC group')
    content=['BT /Label 14 Tf 12 222 Td (Four-component PDF blending) Tj ET']
    xobjects=[]
    for i in range(4):
        space='[/ICCBased 100 0 R]' if i==3 else '/DeviceCMYK'
        program='/C cs .1 .2 .3 .1 scn 0 0 144 60 re f /A gs .6 .1 .2 .3 scn 24 12 96 36 re f'
        if i==2:
            program='/Custom gs .2 .4 .6 rg 0 0 144 60 re f /Reset gs .2 .4 .6 rg 24 12 96 36 re f'
        objects[20+i]=form(program,'/BBox [0 0 144 60] /Group << /S /Transparency /I true /CS '+space+' >> /Resources << /ColorSpace << /C '+space+' >> /ExtGState << /A '+('31' if i==1 else '30')+' 0 R /Custom 32 0 R /Reset 33 0 R >> >>')
        x=12+(i%2)*180;y=132-(i//2)*92
        content.append(f'BT /Label 8 Tf {x} {y+67} Td ({labels[i]}) Tj ET')
        content.append(f'q 1 0 0 1 {x} {y} cm /G{i} Do Q')
        xobjects.append(f'/G{i} {20+i} 0 R')
    content.append('BT /Label 8 Tf 12 19 Td (Native ink components are retained until group conversion. ICC data are authored test transforms.) Tj ET')
    return document('/MediaBox [0 0 360 240] /Resources << /Font << /Label 5 0 R >> /XObject << '+' '.join(xobjects)+' >> >>',stream='\n'.join(content),extra=objects)


def main():
    parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    path=Path(__file__).resolve().parents[1]/'assets/pdf/cmyk-blending.pdf';data=build()
    if args.check:
        assert path.read_bytes()==data,'Regenerate the CMYK blending fixture'
        print('PDF CMYK blending fixture: generated bytes verified')
    else:path.write_bytes(data);print(f'Wrote {path.name}')


if __name__=='__main__':main()
