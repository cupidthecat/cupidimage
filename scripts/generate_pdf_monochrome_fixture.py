#!/usr/bin/env python3
"""Build the owned monochrome dropout sample from the pinned test font."""

import argparse
from pathlib import Path
from test_pdf_monochrome_pages import FONT, METRICS
from test_pdf_page_hinting import fixture

CONTENT = """
BT /Label 14 Tf 12 158 Td (Monochrome TrueType scan policies) Tj ET
BT /Label 9 Tf 12 141 Td (Use --pdf-tt-hinting without --pdf-text-aa.) Tj ET
BT /Label 9 Tf 12 120 Td (Simple, simple without stubs, disabled, smart:) Tj ET
BT /F 12 Tf 20.25 104 Td (ABCEFGHI) Tj ET
BT /Label 9 Tf 12 83 Td (Composite child policies and parent override:) Tj ET
BT /F 12 Tf 20.25 68 Td (QR) Tj ET
BT /Label 9 Tf 12 45 Td (Rotated and stretched conditional scan controls:) Tj ET
BT /F 12 Tf 0 1 -1 0 22.25 18 Tm (J) Tj ET
BT /F 12 Tf 2 0 0 1 60.25 18 Tm (K) Tj ET
"""
PAGE = b"""<< /Type /Page /Parent 2 0 R /Contents 4 0 R /MediaBox [0 0 280 180]
/Resources << /Font << /F 5 0 R /Label 11 0 R >> >> >>"""
LABEL = b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>"


def build():
    return fixture(
        CONTENT,
        font_data=FONT,
        font_name="CupidImageScanPolicies",
        metrics=METRICS,
        extra={3: PAGE, 11: LABEL},
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = Path(__file__).resolve().parents[1] / "assets/pdf/native-monochrome-hinting.pdf"
    if args.check:
        assert path.read_bytes() == build(), "Regenerate the monochrome hinting fixture"
        print("PDF monochrome fixture: generated bytes verified")
    else:
        path.write_bytes(build())
